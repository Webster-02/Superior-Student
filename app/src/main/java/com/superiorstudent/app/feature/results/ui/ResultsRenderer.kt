/**
 * Results presentation only. Term/grade values are supplied by the existing ERP extractor.
 * No missing marks, grades, or credits are generated by the renderer.
 */
class ResultsRenderer(
    private val activity: Context,
    private val sectionHeadingFactory: (String, String) -> View,
    private val tableSectionFactory: (String, TableData) -> View,
    private val emptyStateFactory: (String, String) -> View,
    private val onSemesterSelected: (String) -> Unit,
    private val onRetry: () -> Unit = {}
) {
    private val regularTypeface: Typeface
        get() = ResourcesCompat.getFont(activity, R.font.poppins)
            ?: Typeface.create("sans-serif", Typeface.NORMAL)

    private val mediumTypeface: Typeface
        get() = ResourcesCompat.getFont(activity, R.font.poppins_medium)
            ?: Typeface.create("sans-serif-medium", Typeface.NORMAL)

    fun render(container: LinearLayout, data: ModuleData) {
        container.removeAllViews()

        if (data.academicResults.isNotEmpty()) {
            renderStructuredResults(container, data.academicResults, data.academicResults.last().term)
            return
        }

        // Avoid rendering a nested term-summary table as if its header described course rows.
        val malformedNestedResults = data.tables.any { table ->
            hasHeader(table.headers, "term") &&
                hasHeader(table.headers, "grade points") &&
                hasHeader(table.headers, "total credits") &&
                table.rows.any { row ->
                    row.firstOrNull()?.contains("SPRING", true) == true ||
                        row.firstOrNull()?.contains("FALL", true) == true
                }
        }
        if (malformedNestedResults) {
            container.addView(ErrorState.create(
                activity,
                "Results need a refresh",
                "The ERP returned a nested semester table, but separate course rows were not readable. Retry to sync the latest results.",
                onRetry
            ))
            applyTypography(container)
            return
        }

        if (data.semesterOptions.isNotEmpty()) {
            container.addView(createLegacySemesterSelector(data.semesterOptions))
        }

        val resultTables = data.tables.filter { table ->
            table.headers.any { header ->
                header.contains("subject", true) || header.contains("course", true) ||
                    header.contains("marks", true) || header.contains("obtained", true) ||
                    header.contains("grade", true) || header.contains("credit", true)
            }
        }
        if (resultTables.isNotEmpty()) {
            container.addView(sectionHeadingFactory(
                "Semester results",
                "Course marks, credits and grade information returned by the ERP"
            ))
            val list = ListCard.resultsContainer(activity)
            var addedRows = 0
            resultTables.forEach { table ->
                table.rows.forEach { row ->
                    legacyResultRow(table.headers, row)?.let { rendered ->
                        if (addedRows > 0) list.addView(ListCard.divider(activity))
                        list.addView(rendered)
                        addedRows++
                    }
                }
            }
            if (addedRows > 0) container.addView(list)
        }

        // Keep non-course tables, such as semester notes or other academic details.
        val otherTables = data.tables.filterNot { resultTables.contains(it) }
        otherTables.take(6).forEachIndexed { index, table ->
            container.addView(tableSectionFactory(
                table.title.ifBlank { if (index == 0) "Academic details" else "Additional details" },
                table
            ))
        }

        val resultRecords = data.records.mapNotNull { record ->
            if (record.headers.any { it.equals("Semester options", true) }) return@mapNotNull null
            val values = record.values.map(ParsingUtils::cleanDisplayText).filter(String::isNotBlank)
            if (values.size < 2) null else values
        }.distinctBy { it.joinToString("|").lowercase(Locale.US) }

        if (resultTables.isEmpty() && resultRecords.isNotEmpty()) {
            container.addView(sectionHeadingFactory(
                "Semester results",
                "Academic records returned by the ERP"
            ))
            val list = ListCard.resultsContainer(activity)
            resultRecords.take(60).forEachIndexed { index, values ->
                if (index > 0) list.addView(ListCard.divider(activity))
                list.addView(ListCard.resultRow(
                    activity,
                    values.first(),
                    values.drop(1).joinToString(" · "),
                    null
                ))
            }
            container.addView(list)
        }

        val pageMessage = data.lines.firstOrNull {
            it.contains("no result", true) ||
                it.contains("not uploaded", true) ||
                it.contains("no record", true) ||
                it.contains("result is not", true) ||
                it.contains("not available", true)
        }
        if (resultTables.isEmpty() && resultRecords.isEmpty() && data.cards.isEmpty() && otherTables.isEmpty()) {
            container.addView(EmptyState.create(
                activity,
                "Results are not available yet",
                pageMessage ?: "No published result record was returned by the ERP. Results will appear here when the university publishes them."
            ))
        }
        applyTypography(container)
    }

    private fun renderStructuredResults(
        container: LinearLayout,
        terms: List<AcademicTermResult>,
        selectedTerm: String
    ) {
        container.removeAllViews()
        val term = terms.firstOrNull { it.term == selectedTerm } ?: terms.lastOrNull()
        if (term == null) {
            container.addView(EmptyState.create(
                activity,
                "Results are not available yet",
                "No semester result information was returned by the ERP."
            ))
            return
        }

        val published = hasPublishedResults(term)
        val cgpa = terms.asReversed().firstNotNullOfOrNull { validGpa(it.cgpa) }
        val sgpa = validGpa(term.gpa)
        val creditHoursAllTerms = aggregateTotalCredits(terms)
        HeroCard.results(activity, cgpa, sgpa, creditHoursAllTerms)?.let(container::addView)

        container.addView(createTermSelector(terms, term.term) { chosen ->
            if (chosen != term.term) renderStructuredResults(container, terms, chosen)
        })

        createAdditionalMetrics(term)?.let(container::addView)

        val selectedCredits = termCreditHours(term)
        container.addView(createSemesterHeading(
            semesterTitle(term.term),
            selectedCredits?.let { "$it credit hrs" }
        ))

        if (!published) {
            container.addView(EmptyState.create(
                activity,
                "Results not published yet",
                "The ERP has not provided published marks or grades for ${term.term}. Course names and credits are shown only where available; no grades are estimated."
            ))
        }

        if (term.courses.isEmpty()) {
            container.addView(EmptyState.create(
                if (published) "No course rows available" else "Results not published yet",
                "The ERP did not return separate course records for ${term.term}."
            ))
        } else {
            val list = ListCard.resultsContainer(activity)
            var addedRows = 0
            term.courses.forEach { course ->
                courseRow(course, published)?.let { row ->
                    if (addedRows > 0) list.addView(ListCard.divider(activity))
                    list.addView(row)
                    addedRows++
                }
            }
            if (addedRows > 0) container.addView(list)
            else container.addView(EmptyState.create(
                "No course details available",
                "The ERP did not return any readable course names or credit details for ${term.term}."
            ))
        }
        applyTypography(container)
    }

    private fun createTermSelector(
        terms: List<AcademicTermResult>,
        selectedTerm: String,
        onSelected: (String) -> Unit
    ): View {
        val scroll = HorizontalScrollView(activity).apply {
            isHorizontalScrollBarEnabled = false
            clipToPadding = false
            overScrollMode = View.OVER_SCROLL_NEVER
            setPadding(dp(16), dp(5), dp(16), dp(5))
            layoutParams = LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT,
                ViewGroup.LayoutParams.WRAP_CONTENT
            ).apply {
                topMargin = dp(6)
                bottomMargin = dp(5)
            }
        }
        val row = LinearLayout(activity).apply { orientation = LinearLayout.HORIZONTAL }
        terms.forEach { term ->
            val selected = term.term == selectedTerm
            row.addView(TextView(activity).apply {
                text = semesterChipLabel(term.term)
                textSize = 13f
                setTextColor(if (selected) Palette.segmentInk(activity) else Palette.ink(activity))
                typeface = mediumTypeface
                includeFontPadding = false
                gravity = Gravity.CENTER
                minHeight = dp(48)
                setPadding(dp(18), dp(10), dp(18), dp(10))
                background = rounded(
                    if (selected) Palette.segment(activity) else Palette.card(activity),
                    999f,
                    if (selected) null else Palette.stroke(activity)
                )
                contentDescription = "Show ${term.term} results" + if (selected) ", selected" else ""
                isClickable = true
                isFocusable = true
                layoutParams = LinearLayout.LayoutParams(
                    ViewGroup.LayoutParams.WRAP_CONTENT, dp(48)
                ).apply { setMargins(0, 0, dp(8), 0) }
                setOnClickListener { onSelected(term.term) }
            })
        }
        scroll.addView(row)
        return scroll
    }

    private fun createLegacySemesterSelector(options: List<String>): View {
        val scroll = HorizontalScrollView(activity).apply {
            isHorizontalScrollBarEnabled = false
            clipToPadding = false
            overScrollMode = View.OVER_SCROLL_NEVER
            setPadding(dp(16), dp(5), dp(16), dp(5))
            layoutParams = LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT,
                ViewGroup.LayoutParams.WRAP_CONTENT
            ).apply { topMargin = dp(5) }
        }
        val row = LinearLayout(activity).apply { orientation = LinearLayout.HORIZONTAL }
        var selectedOption = options.firstOrNull().orEmpty()
        fun drawOptions() {
            row.removeAllViews()
            options.forEach { option ->
                val selected = option == selectedOption
                row.addView(TextView(activity).apply {
                    text = semesterChipLabel(option)
                    textSize = 13f
                    setTextColor(if (selected) Palette.segmentInk(activity) else Palette.ink(activity))
                    typeface = mediumTypeface
                    includeFontPadding = false
                    gravity = Gravity.CENTER
                    minHeight = dp(48)
                    setPadding(dp(18), dp(10), dp(18), dp(10))
                    background = rounded(
                        if (selected) Palette.segment(activity) else Palette.card(activity),
                        999f,
                        if (selected) null else Palette.stroke(activity)
                    )
                    contentDescription = "Show $option results" + if (selected) ", selected" else ""
                    isClickable = true
                    isFocusable = true
                    layoutParams = LinearLayout.LayoutParams(
                        ViewGroup.LayoutParams.WRAP_CONTENT, dp(48)
                    ).apply { setMargins(0, 0, dp(8), 0) }
                    setOnClickListener {
                        selectedOption = option
                        drawOptions()
                        onSemesterSelected(option)
                    }
                })
            }
        }
        drawOptions()
        scroll.addView(row)
        return scroll
    }

    private fun createSemesterHeading(title: String, credits: String?): View =
        LinearLayout(activity).apply {
            orientation = LinearLayout.HORIZONTAL
            gravity = Gravity.CENTER_VERTICAL
            setPadding(dp(16), dp(14), dp(16), dp(8))
            layoutParams = LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT,
                ViewGroup.LayoutParams.WRAP_CONTENT
            )
            addView(TextView(activity).apply {
                text = title
                textSize = 20f
                setTextColor(Palette.ink(activity))
                typeface = mediumTypeface
                includeFontPadding = false
            }, LinearLayout.LayoutParams(0, ViewGroup.LayoutParams.WRAP_CONTENT, 1f))
            credits?.let {
                addView(TextView(activity).apply {
                    text = it
                    textSize = 13f
                    setTextColor(Palette.ink2(activity))
                    typeface = regularTypeface
                    includeFontPadding = false
                })
            }
        }

    private fun createAdditionalMetrics(term: AcademicTermResult): View? {
        val extras = listOfNotNull(
            validNonNegativeMetric(term.gradePoints)?.let { "Grade points" to it },
            validNonNegativeMetric(term.earnedCredits)?.let { "Earned credits" to it }
        )
        if (extras.isEmpty()) return null

        return LinearLayout(activity).apply {
            orientation = LinearLayout.HORIZONTAL
            layoutParams = LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT,
                ViewGroup.LayoutParams.WRAP_CONTENT
            ).apply { setMargins(dp(16), dp(4), dp(16), dp(4)) }
            extras.forEachIndexed { index, (label, value) ->
                addView(LinearLayout(activity).apply {
                    orientation = LinearLayout.VERTICAL
                    background = rounded(
                        if (index == 0) Palette.lav(activity) else Palette.sky(activity),
                        16f,
                        null
                    )
                    setPadding(dp(12), dp(9), dp(12), dp(9))
                    addView(TextView(activity).apply {
                        text = label
                        textSize = 11f
                        setTextColor(Palette.ink2(activity))
                        typeface = regularTypeface
                        includeFontPadding = false
                    })
                    addView(TextView(activity).apply {
                        text = value
                        textSize = 17f
                        setTextColor(Palette.ink(activity))
                        typeface = mediumTypeface
                        includeFontPadding = false
                        setFontFeatureSettings("tnum")
                    })
                }, LinearLayout.LayoutParams(
                    0, ViewGroup.LayoutParams.WRAP_CONTENT, 1f
                ).apply { if (index > 0) marginStart = dp(8) })
            }
        }
    }

    private fun courseRow(course: AcademicCourseResult, published: Boolean): View? {
        val name = ParsingUtils.cleanDisplayText(course.course).takeIf(String::isNotBlank) ?: return null
        val detailParts = mutableListOf<String>()
        validNonNegativeMetric(course.credits)?.let { detailParts.add("$it cr") }
        val marks = course.marksObtained.trim()
        if (published && marks.isNotBlank()) detailParts.add(marks)
        validNonNegativeMetric(course.gradePoints)?.takeIf { published }?.let { detailParts.add("$it pts") }
        course.midGrade.trim().takeIf { published && it.isNotBlank() }?.let { detailParts.add("Mid $it") }
        val finalGrade = course.finalGrade.trim().takeIf { published && it.isNotBlank() }

        return ListCard.resultRow(
            activity,
            name,
            detailParts.joinToString(" · "),
            finalGrade
        )
    }

    private fun legacyResultRow(headers: List<String>, values: List<String>): View? {
        if (values.none { it.isNotBlank() }) return null
        fun valueFor(vararg names: String): String {
            val index = headers.indexOfFirst { header -> names.any { header.contains(it, true) } }
            return if (index >= 0 && index < values.size) ParsingUtils.cleanDisplayText(values[index]) else ""
        }
        val title = valueFor("subject", "course name", "course title", "course")
            .ifBlank { values.firstOrNull().orEmpty() }
        if (title.isBlank() || title.equals("course", true) || title.equals("subject", true)) return null

        val courseCode = valueFor("subject code", "course code", "code")
        val credits = valueFor("credits", "credit hours", "cr")
        val marks = valueFor("marks obtained", "marks", "score")
        val maximum = valueFor("maximum marks", "max marks", "maximum", "out of")
        val gradePoints = valueFor("grade points", "grade pts", "points")
        val midGrade = valueFor("mid grade")
        val finalGrade = valueFor("final grade", "letter grade", "grade")

        val details = mutableListOf<String>()
        validNonNegativeMetric(credits)?.let { details.add("$it cr") }
        if (marks.isNotBlank()) details.add(if (maximum.isNotBlank() && !marks.contains("/")) "$marks / $maximum" else marks)
        if (gradePoints.isNotBlank()) details.add("$gradePoints pts")
        if (midGrade.isNotBlank()) details.add("Mid $midGrade")
        if (courseCode.isNotBlank()) details.add(courseCode)
        return ListCard.resultRow(activity, title, details.joinToString(" · "), finalGrade.takeIf(String::isNotBlank))
    }

    private fun hasPublishedResults(term: AcademicTermResult): Boolean {
        if (validPositiveNumber(term.gradePoints) != null || validGpa(term.gpa) != null || validGpa(term.cgpa) != null) return true
        return term.courses.any { course ->
            course.finalGrade.isNotBlank() || course.midGrade.isNotBlank() ||
                validPositiveNumber(course.marksObtained) != null ||
                validPositiveNumber(course.gradePoints) != null
        }
    }

    private fun validGpa(value: String): String? {
        val number = value.replace(",", "").trim().toDoubleOrNull() ?: return null
        if (!number.isFinite() || number <= 0.0 || number > 4.0) return null
        return String.format(Locale.US, "%.2f", number).trimEnd('0').trimEnd('.')
    }

    private fun validPositiveNumber(value: String): Double? {
        val numeric = Regex("""\d+(?:\.\d+)?""").find(value.replace(",", ""))?.value ?: return null
        val number = numeric.toDoubleOrNull() ?: return null
        return number.takeIf { it.isFinite() && it > 0.0 }
    }

    private fun validNonNegativeMetric(value: String): String? {
        val cleaned = value.trim()
        if (cleaned.isBlank()) return null
        val number = cleaned.replace(",", "").toDoubleOrNull() ?: return cleaned
        if (!number.isFinite() || number < 0.0) return null
        return formatNumber(number)
    }

    private fun aggregateTotalCredits(terms: List<AcademicTermResult>): String? {
        if (terms.isEmpty()) return null
        val coursesByTerm = terms.map { it.courses }
        if (coursesByTerm.all { it.isNotEmpty() }) {
            val credits = coursesByTerm.flatten().map { it.credits.replace(",", "").trim().toDoubleOrNull() }
            if (credits.all { it != null && it.isFinite() && it >= 0.0 }) {
                return formatNumber(credits.filterNotNull().sum()).takeIf { it != "0" }
            }
        }
        // Fall back only to actual per-term summary values when they are all available.
        val totals = terms.map { it.totalCredits.replace(",", "").trim().toDoubleOrNull() }
        if (totals.all { it != null && it.isFinite() && it >= 0.0 }) {
            return formatNumber(totals.filterNotNull().sum()).takeIf { it != "0" }
        }
        return null
    }

    private fun termCreditHours(term: AcademicTermResult): String? {
        if (term.courses.isNotEmpty()) {
            val credits = term.courses.map { it.credits.replace(",", "").trim().toDoubleOrNull() }
            if (credits.all { it != null && it.isFinite() && it >= 0.0 }) {
                val sum = formatNumber(credits.filterNotNull().sum())
                if (sum != "0") return sum
            }
        }
        validNonNegativeMetric(term.totalCredits)?.let { value ->
            if ((value.replace(",", "").toDoubleOrNull() ?: 0.0) > 0.0) return value
        }
        return null
    }

    private fun formatNumber(value: Double): String =
        if (kotlin.math.abs(value - value.roundToInt()) < 0.001) {
            value.roundToInt().toString()
        } else {
            String.format(Locale.US, "%.1f", value).trimEnd('0').trimEnd('.')
        }

    private fun semesterTitle(value: String): String {
        val match = Regex("""(?i)\bsemester\s*(\d+)\b""").find(value)
        return match?.groupValues?.getOrNull(1)?.let { "Semester $it" }
            ?: value.trim().ifBlank { "Semester results" }
    }

    private fun semesterChipLabel(value: String): String {
        val match = Regex("""(?i)\bsemester\s*(\d+)\b""").find(value)
        if (match != null) return "Sem ${match.groupValues[1]}"
        val term = value.trim()
        return if (term.length > 15) term.take(15).trimEnd() + "…" else term
    }

    private fun hasHeader(headers: List<String>, fragment: String): Boolean =
        headers.any { it.trim().equals(fragment, true) || it.contains(fragment, true) }

    private fun applyTypography(view: View) {
        when (view) {
            is TextView -> {
                val style = view.typeface?.style ?: Typeface.NORMAL
                view.typeface = if (style and Typeface.BOLD != 0) {
                    Typeface.create(mediumTypeface, Typeface.BOLD)
                } else regularTypeface
                view.includeFontPadding = false
            }
            is ViewGroup -> for (index in 0 until view.childCount) applyTypography(view.getChildAt(index))
        }
    }

    private fun rounded(color: Int, radiusDp: Float, strokeColor: Int?): GradientDrawable =
        GradientDrawable().apply {
            shape = GradientDrawable.RECTANGLE
            setColor(color)
            cornerRadius = dp(radiusDp).toFloat()
            strokeColor?.let { setStroke(dp(1), it) }
        }

    private fun dp(value: Int): Int = (value * activity.resources.displayMetrics.density).roundToInt()
}
